// ---------- lay out the calendar ----------
// Every 7th day is a Trial day (weekly cumulative assessment). Every 4th Trial is a Benchmark (contest-style).
const sessions = []; const units = []; const skills = {};
let day = 1, week = 1, monthPack = (d) => `m${String(Math.ceil(d / 28)).padStart(2, '0')}`;
function pushTrialIfNeeded() {
  if (day % 7 === 0) {
    const isBench = day % 28 === 0;
    sessions.push({ id: `d${String(day).padStart(3, '0')}`, day, type: isBench ? 'benchmark' : 'trial', title: isBench ? `Benchmark ${day / 28}` : `Weekly Trial ${day / 7}`, unit: currentUnit, skills: [], pack: monthPack(day) });
    day++;
  }
}
let currentUnit = null;
for (const u of UNITS) {
  currentUnit = u.id; const start = day;
  for (const [title, sk, book, type] of u.lessons) {
    pushTrialIfNeeded();
    if (day > 365) break;
    const isLast = day === 365;
    sessions.push({ id: `d${String(day).padStart(3, '0')}`, day, type: isLast ? 'benchmark' : (type || 'lesson'), title, unit: u.id, unitName: u.name, skills: sk, book: book || null, pack: monthPack(day) });
    for (const s of sk) if (!skills[s]) skills[s] = { name: nameFor(s), unit: u.id, w: s.endsWith('contest') || s.startsWith('fn.') ? 0.5 : 1, firstDay: day };
    day++;
  }
  pushTrialIfNeeded();
  units.push({ id: u.id, name: u.name, startDay: start, endDay: day - 1 });
}
while (day <= 365) { // fill to 365 with review days if a unit list is short
  pushTrialIfNeeded(); if (day > 365) break;
  sessions.push({ id: `d${String(day).padStart(3, '0')}`, day, type: 'lesson', title: 'Cumulative review', unit: 'FN', unitName: 'Final Synthesis', skills: ['fn.review'], pack: monthPack(day) }); day++;
}
sessions.length = Math.min(sessions.length, 365);

